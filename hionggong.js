function 推導(白讀) {
  let 韻母 = 韻母規則(白讀);
  let 聲母 = 聲母規則(白讀);
  const 聲調 = 聲調規則(白讀);

  if (is`入聲`) {
    if (韻母.endsWith('m')) 韻母 = 韻母.slice(0, -1) + 'p';
    else if (韻母.endsWith('n')) 韻母 = 韻母.slice(0, -1) + 't';
    else if (韻母.endsWith('ng')) 韻母 = 韻母.slice(0, -2) + 'k';
  }

  // 疑母模韻的「吳、五」等以後鼻音自成音節；去聲「誤、悟」等則一般讀 ngu。
  if (韻母 === 'ng') {
    if (聲母 === 'ng' && !is`去聲`) 聲母 = '';
    else 韻母 = 'u';
  }

  // 脣齒音後不保留低、中元音前的 i 介音（王 vong、方 fong）。
  // y 本身已表示介音；複合韻起首的 i 不重複拼寫（yien → yen，yiong → yong），一併處理。
  if (['f', 'v', 'y'].includes(聲母) && /^i([aeo]|u(?!$))/.test(韻母)) 韻母 = 韻母.slice(1);
  // 知、莊、章組後山攝三四等的 i 介音不保留；精組仍保留（線 sien、善 sen）。
  if (is`知莊章組` && 韻母.startsWith('ie')) 韻母 = 韻母.slice(1);

  return { 聲母, 韻母, 聲調 };
}

function 轉IPA({ 聲母, 韻母, 聲調 }) {
  const 音節鼻音 = { m: 'm̩', n: 'n̩', ng: 'ŋ̍' }[韻母];
  聲母 = {
    '': 選項.零聲母加喉塞 && !音節鼻音 ? 'ʔ' : '',
    'b': 'p', 'p': 'pʰ', 'm': 'm', 'f': 'f', 'v': 'v',
    'd': 't', 't': 'tʰ', 'l': 'l', 'z': 't͡s', 'c': 't͡sʰ', 's': 's',
    'g': 'k', 'k': 'kʰ', 'ng': 韻母.startsWith('i') ? 選項.腭化鼻音符號 : 'ŋ', 'h': 'h', 'y': 'j',
  }[聲母];
  韻母 = 韻母
    .replace(/(?<!^)i$/, 'j').replace(/(?<!^)u$/, 'w').replace('ng', 'ŋ')
    .replace(/[eo]/, 元音 => 選項.中元音.split('｜')['eo'.indexOf(元音)])
    .replace(/^i(?=[aeou])/, 聲母 === 選項.腭化鼻音符號 ? '' : 'ʲ');
  韻母 = 音節鼻音 || (/[mnŋptk]$/.test(韻母) ? 韻母.slice(0, -1) + 選項.無聲除阻標記.replace(/.*（|）.*/g, '').split(' ')['mnŋptk'.indexOf(韻母.slice(-1))] : 韻母);
  return { 聲母, 韻母, 聲調 };
}

function 標調({ 聲母, 韻母, 聲調 }) {
  聲調 = {
    數字調值: ['', '¹³', '¹¹', '³¹', '⁵³', '³¹', '⁵³'],
    折線調值: ['', '˩˧', '˩', '˧˩', '˥˧', '˧˩', '˥˧'],
  }[選項.標調方式]?.[聲調] || 聲調;
  const 音節 = 聲母 + 韻母 + 聲調;
  return 選項.標調方式 === '符號調號' ?
    音節.replace(/(\D*[aeoɛɔ]|\D*[iu](?!\d)|\D*[iumnŋ])(\D*)(\d)/g, (_, $1, $2, $3) => $1 + (isIPA ? ' ᷅̀᷆᷇᷆᷇' : ' ́̄̆̀̆̀')[+$3] + $2) :
    音節;
}

function 格式化(白讀) {
  let 讀音 = 推導(白讀);
  if (isIPA) 讀音 = 轉IPA(讀音);
  return 標調(讀音);
}

const 文讀 = 選項.文白讀 === '僅白讀' ? null : 格式化(false);
const 白讀 = 選項.文白讀 === '僅文讀' ? null : 格式化(true);

if (文讀 === null) return 白讀;
if (白讀 === null || 文讀 === 白讀) return 文讀;
return 文讀 + '\n' + 白讀;
